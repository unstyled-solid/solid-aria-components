import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const root = process.cwd();
const require = createRequire(path.join(root,'package.json'));
const ts = require('typescript');
const config = ts.readConfigFile(path.join(root,'tsconfig.wave.json'),ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config,ts.sys,root);
parsed.options.paths['solid-aria-components']=['packages/react-aria-components/exports/index.ts'];
parsed.options.paths['solid-aria-components/*']=['packages/react-aria-components/exports/*'];
parsed.options.noEmit=true;
const dir=path.join(root,'docs-website/upstream/packages/dev/s2-docs/pages/react-aria');
const files=['NavigationTree','Virtualizer'].flatMap(f=>fs.readdirSync(path.join(dir,f)).filter(n=>/^solid-demo.*\.tsx$/.test(n)).map(n=>path.join(dir,f,n)));
const program=ts.createProgram([path.join(root,'test/intl.d.ts'),...files],parsed.options);
const errors=ts.getPreEmitDiagnostics(program);
const owned=errors.filter(e=>/\/(NavigationTree|Virtualizer)\//.test(e.file?.fileName||''));
console.log(ts.formatDiagnosticsWithColorAndContext(owned,{getCanonicalFileName:f=>f,getCurrentDirectory:()=>root,getNewLine:()=> '\n'}));
console.log(JSON.stringify({total:errors.length,owned:owned.length}));
for (const error of errors.filter(e=>!owned.includes(e))) console.log(JSON.stringify({file:error.file?.fileName,code:error.code,message:ts.flattenDiagnosticMessageText(error.messageText,' ')}));
process.exitCode=owned.length?1:0;
